def _device_ratio() -> float:
    app = QGuiApplication.instance()
    screen = app.primaryScreen() if app else None
    return max(1.0, screen.devicePixelRatio()) if screen else 1.0


def _render_svg(svg: str, size: int) -> QPixmap:
    ratio = _device_ratio()
    pixmap = QPixmap(int(size * ratio), int(size * ratio))
    pixmap.fill(Qt.GlobalColor.transparent)
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, pixmap.width(), pixmap.height()))
    painter.end()
    pixmap.setDevicePixelRatio(ratio)
    return pixmap


@lru_cache(maxsize=512)
def pixmap(name: str, color: str, size: int = 18, stroke: float = 2.0) -> QPixmap:
    if name not in LUCIDE:
        raise KeyError(f"Bilinmeyen ikon: {name}")
    body = LUCIDE[name].replace("currentColor", color)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
           f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    return _render_svg(svg, size)


def icon(name: str, color: str, *, active: str | None = None, checked: str | None = None,
         disabled: str | None = None, size: int = 18) -> QIcon:
    """Durumlara göre farklı renklenen QIcon (normal / hover / seçili / pasif)."""
    result = QIcon()
    result.addPixmap(pixmap(name, color, size), QIcon.Mode.Normal, QIcon.State.Off)
    if active:
        result.addPixmap(pixmap(name, active, size), QIcon.Mode.Active, QIcon.State.Off)
    if checked:
        result.addPixmap(pixmap(name, checked, size), QIcon.Mode.Normal, QIcon.State.On)
        result.addPixmap(pixmap(name, checked, size), QIcon.Mode.Active, QIcon.State.On)
    if disabled:
        result.addPixmap(pixmap(name, disabled, size), QIcon.Mode.Disabled, QIcon.State.Off)
    return result


@lru_cache(maxsize=32)
def logo_pixmap(size: int, c1: str, c2: str) -> QPixmap:
    return _render_svg(LOGO_SVG.format(c1=c1, c2=c2), size)


def logo_icon(c1: str, c2: str) -> QIcon:
    result = QIcon()
    for s in (16, 24, 32, 48, 64, 128, 256):
        result.addPixmap(logo_pixmap(s, c1, c2))
    return result


def icon_size(px: int) -> QSize:
    return QSize(px, px)
